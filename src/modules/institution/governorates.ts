export function governorateMatches(
  institutionGovernorate: string | null | undefined,
  universityGovernorate: string | null | undefined,
) {
  return (
    !!institutionGovernorate &&
    !!universityGovernorate &&
    institutionGovernorate === universityGovernorate
  );
}
